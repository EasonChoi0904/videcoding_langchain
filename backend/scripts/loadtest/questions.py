def pick_pool(n: int, mode: str = "mock", seed: int | None = None) -> list[str]:
    """从题库随机取 n 条(允许重复,贴近真实重问分布;seed 固定时结果可复现)。"""
    rnd = random.Random(seed)
    if mode == "real":
        pool = _REAL_POOL
    elif mode == "mix":
        pool = _MOCK_POOL + _REAL_POOL
    else:
        pool = _MOCK_POOL
    return [rnd.choice(pool) for _ in range(n)]


